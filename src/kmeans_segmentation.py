"""Step 7: KMeans clustering of customers into four tiers, compared with the rule-based segments.

Run after 03_customer_360.py and 04_segmentation.py:

    python src/kmeans_segmentation.py

Writes:
    data/cleaned/customer_360.csv      (adds kmeans_cluster and kmeans_tier columns)
    reports/KMEANS_SEGMENTS.md         (method, assumption checks and results with the real numbers)
    figures/kmeans_silhouette.png      (how well-separated the clusters are for k = 2..7)
    figures/kmeans_segments.png        (the four tiers on balance vs. transaction value)
"""

from __future__ import annotations

from dataclasses import dataclass
from pathlib import Path

import numpy as np
import pandas as pd
from sklearn.cluster import KMeans
from sklearn.metrics import adjusted_rand_score, silhouette_score
from sklearn.preprocessing import StandardScaler

FEATURES = ["total_balance", "transaction_value", "transaction_count", "product_count", "total_loan_value"]
VALUE = ["total_balance", "transaction_value"]
ENGAGEMENT = ["product_count", "transaction_count"]
SEED = 42
SILHOUETTE_SAMPLE = 10_000


@dataclass
class ClusteringResult:
    data: pd.DataFrame
    skew_before: pd.Series
    skew_after: pd.Series
    log_features: list[str]
    silhouette_by_k: dict[int, float]
    summary: pd.DataFrame
    agreement_with_rules: float | None


def prepare_features(df: pd.DataFrame, skew_threshold: float = 1.0):
    """KMeans uses Euclidean distance, so it works best on roughly symmetric, equally scaled features.

    Money and count columns are usually right-skewed: log-transform those with skew above the
    threshold, then standardize everything to mean 0 and standard deviation 1.
    """
    X = df[FEATURES].astype(float).clip(lower=0)
    skew_before = X.skew()
    log_features = [c for c in FEATURES if skew_before[c] > skew_threshold]
    X[log_features] = np.log1p(X[log_features])
    skew_after = X.skew()
    return StandardScaler().fit_transform(X), skew_before, skew_after, log_features


def silhouette_scan(X: np.ndarray, ks=range(2, 8)) -> dict[int, float]:
    rng = np.random.default_rng(SEED)
    idx = rng.choice(len(X), size=min(SILHOUETTE_SAMPLE, len(X)), replace=False)
    scores = {}
    for k in ks:
        labels = KMeans(n_clusters=k, n_init=10, random_state=SEED).fit_predict(X)
        scores[k] = float(silhouette_score(X[idx], labels[idx]))
    return scores


def name_tiers(df: pd.DataFrame, labels: np.ndarray) -> dict[int, str]:
    """Name each cluster by whether its median value and engagement are above the overall median."""
    value_score = df[VALUE].rank(pct=True).mean(axis=1)
    engagement_score = df[ENGAGEMENT].rank(pct=True).mean(axis=1)
    names = {}
    for cluster in np.unique(labels):
        mask = labels == cluster
        value = "High Value" if value_score[mask].median() >= value_score.median() else "Low Value"
        engagement = "High Engagement" if engagement_score[mask].median() >= engagement_score.median() else "Low Engagement"
        names[int(cluster)] = f"{value}, {engagement}"
    # Two clusters can land in the same quadrant; keep their names distinct
    counts: dict[str, int] = {}
    for cluster, name in sorted(names.items()):
        counts[name] = counts.get(name, 0) + 1
        if counts[name] > 1:
            names[cluster] = f"{name} ({counts[name]})"
    return names


def cluster_customers(df: pd.DataFrame, k: int = 4, scan: bool = True) -> ClusteringResult:
    X, skew_before, skew_after, log_features = prepare_features(df)
    model = KMeans(n_clusters=k, n_init=10, random_state=SEED)
    labels = model.fit_predict(X)
    names = name_tiers(df, labels)

    out = df.copy()
    out["kmeans_cluster"] = labels
    out["kmeans_tier"] = [names[int(c)] for c in labels]

    summary = out.groupby("kmeans_tier").agg(
        customers=("customer_id", "count"),
        avg_balance=("total_balance", "mean"),
        avg_txn_value=("transaction_value", "mean"),
        avg_products=("product_count", "mean"),
        pct_one_or_two_products=("product_count", lambda s: 100 * (s <= 2).mean()),
    ).round(2).sort_values("avg_balance", ascending=False)
    summary["share_pct"] = (100 * summary["customers"] / len(out)).round(1)

    agreement = None
    if "customer_segment" in out.columns:
        agreement = float(adjusted_rand_score(out["customer_segment"], out["kmeans_tier"]))

    return ClusteringResult(out, skew_before, skew_after, log_features,
                            silhouette_scan(X) if scan else {}, summary, agreement)


def write_report(result: ClusteringResult, path: Path) -> None:
    best_k = max(result.silhouette_by_k, key=result.silhouette_by_k.get) if result.silhouette_by_k else None
    lines = [
        "# KMeans customer tiers",
        "",
        "Generated by `src/kmeans_segmentation.py`.",
        "",
        "## Method",
        "",
        f"- Features: {', '.join(FEATURES)}",
        f"- Log-transformed (skew above 1): {', '.join(result.log_features) or 'none'}; then all features standardized",
        "- KMeans with k = 4, 10 initializations, fixed random seed",
        "",
        "## Assumption checks",
        "",
        "| Feature | Skew before | Skew after |",
        "|---|---|---|",
        *[f"| {f} | {result.skew_before[f]:.2f} | {result.skew_after[f]:.2f} |" for f in FEATURES],
        "",
        "Silhouette score by number of clusters (higher = better separated, sampled):",
        "",
        "| k | Silhouette |",
        "|---|---|",
        *[f"| {k} | {s:.3f} |" for k, s in result.silhouette_by_k.items()],
        "",
    ]
    if best_k is not None:
        lines += [f"k = 4 was kept so the tiers can be compared with the four rule-based segments; "
                  f"the best-separated k in this scan was {best_k}.", ""]
    lines += ["## Tiers", "", result.summary.to_markdown(), ""]
    if result.agreement_with_rules is not None:
        lines += [f"Agreement with the median-rule segments from step 4 (adjusted Rand index): "
                  f"{result.agreement_with_rules:.2f} (1 = identical, 0 = no better than chance).", ""]
    path.write_text("\n".join(lines))


def plot(result: ClusteringResult, figures: Path) -> None:
    import matplotlib

    matplotlib.use("Agg")
    import matplotlib.pyplot as plt

    if result.silhouette_by_k:
        fig, ax = plt.subplots(figsize=(6, 4))
        ax.plot(list(result.silhouette_by_k), list(result.silhouette_by_k.values()), marker="o")
        ax.set(xlabel="Number of clusters (k)", ylabel="Silhouette score", title="Choosing k")
        fig.tight_layout()
        fig.savefig(figures / "kmeans_silhouette.png", dpi=120)
        plt.close(fig)

    data = result.data.sample(min(5000, len(result.data)), random_state=SEED)
    fig, ax = plt.subplots(figsize=(7, 5))
    for tier, group in data.groupby("kmeans_tier"):
        ax.scatter(np.log1p(group["total_balance"]), np.log1p(group["transaction_value"]), s=6, alpha=0.5, label=tier)
    ax.set(xlabel="log(1 + total balance)", ylabel="log(1 + transaction value)", title="KMeans customer tiers (sample)")
    ax.legend(markerscale=3, fontsize=8)
    fig.tight_layout()
    fig.savefig(figures / "kmeans_segments.png", dpi=120)
    plt.close(fig)


def main() -> None:
    path = Path("data/cleaned/customer_360.csv")
    if not path.exists():
        raise SystemExit("Run src/03_customer_360.py (and 04_segmentation.py) first.")
    result = cluster_customers(pd.read_csv(path))
    result.data.to_csv(path, index=False)
    Path("reports").mkdir(exist_ok=True)
    Path("figures").mkdir(exist_ok=True)
    write_report(result, Path("reports/KMEANS_SEGMENTS.md"))
    plot(result, Path("figures"))
    print(result.summary.to_string())
    print(f"\nSilhouette by k: { {k: round(v, 3) for k, v in result.silhouette_by_k.items()} }")
    if result.agreement_with_rules is not None:
        print(f"Agreement with rule-based segments (ARI): {result.agreement_with_rules:.2f}")
    print("\nSaved: reports/KMEANS_SEGMENTS.md, figures/kmeans_silhouette.png, figures/kmeans_segments.png")


if __name__ == "__main__":
    main()
